// Copies the rule files (policies/*.yaml) into lib/policies.generated.ts so the server never reads files at run time.
// Run after changing a policy: node scripts/gen-policies.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../../policies/", import.meta.url));
const pick = (dir) => readdirSync(dir).filter((f) => f.endsWith(".yaml") && f !== "sources.yaml").sort().map((f) => readFileSync(join(dir, f), "utf8"));
const out = `// Generated by scripts/gen-policies.mjs from /policies. Do not edit.\nexport const POLICY_YAML: string[] = ${JSON.stringify(pick(root), null, 0)};\nexport const OVERLAY_YAML: string[] = ${JSON.stringify(pick(join(root, "overlays")), null, 0)};\n`;
writeFileSync(fileURLToPath(new URL("../lib/policies.generated.ts", import.meta.url)), out);
console.log("wrote lib/policies.generated.ts");
